String mapInfografisCategory(int id) {
  switch (id) {
    case 1:
      return "Sosial & Kependudukan";
    case 2:
      return "Ekonomi & Perdagangan";
    case 3:
      return "Pertanian & Pertambangan";
    case 4:
      return "Industri & Energi";
    case 5:
      return "Pariwisata & Transportasi";
    case 6:
      return "Lingkungan Hidup";
    case 7:
      return "Statistik Umum";
    default:
      return "Lainnya";
  }
}
